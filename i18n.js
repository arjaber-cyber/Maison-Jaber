(function () {
  const LANG_KEY = 'hikaya_lang';
  const LANG_NAMES = { en: 'EN', de: 'DE', ar: 'AR' };
  const LANG_LABELS = { en: 'English', de: 'Deutsch', ar: 'العربية' };

  function getLang() {
    return localStorage.getItem(LANG_KEY) || 'en';
  }

  function t(key) {
    const [ns, k] = key.split('.');
    const entry = (window.HIKAYA_TRANSLATIONS[ns] || {})[k] || (window.HIKAYA_TRANSLATIONS.common || {})[k];
    if (!entry) return null;
    const lang = getLang();
    return entry[lang] || entry.en;
  }

  function applyTranslations() {
    const lang = getLang();
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const val = t(el.getAttribute('data-i18n'));
      if (val !== null) el.textContent = val;
    });
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const val = t(el.getAttribute('data-i18n-html'));
      if (val !== null) el.innerHTML = val;
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const val = t(el.getAttribute('data-i18n-placeholder'));
      if (val !== null) el.setAttribute('placeholder', val);
    });

    document.querySelectorAll('.lang-current-label').forEach(el => { el.textContent = LANG_NAMES[lang]; });
  }

  function setLang(lang) {
    localStorage.setItem(LANG_KEY, lang);
    applyTranslations();
    document.dispatchEvent(new CustomEvent('hikaya:langchange', { detail: { lang } }));
  }

  function buildSwitcher() {
    document.querySelectorAll('.lang-pill').forEach(pill => {
      if (pill.dataset.switcherBound) return;
      pill.dataset.switcherBound = '1';
      pill.style.position = 'relative';

      // Wrap the visible label in its own span so re-translating it never
      // touches (and wipes out) the dropdown menu appended below.
      const label = document.createElement('span');
      label.className = 'lang-current-label';
      label.textContent = LANG_NAMES[getLang()];
      pill.textContent = '';
      pill.appendChild(label);

      const menu = document.createElement('div');
      menu.className = 'lang-menu';
      menu.style.cssText = 'display:none; position:absolute; top:calc(100% + 8px); right:0; background:#fff; border:1px solid var(--line, #ddd); border-radius:12px; box-shadow:0 8px 24px rgba(0,0,0,0.12); overflow:hidden; z-index:100; min-width:130px;';
      ['en', 'de', 'ar'].forEach(code => {
        const item = document.createElement('button');
        item.type = 'button';
        item.textContent = LANG_LABELS[code];
        item.style.cssText = 'display:block; width:100%; text-align:left; padding:10px 16px; border:none; background:#fff; font-family:inherit; font-size:13px; font-weight:600; cursor:pointer; color:var(--ink,#222);';
        item.addEventListener('mouseenter', () => item.style.background = 'var(--bg-soft,#f7f7f7)');
        item.addEventListener('mouseleave', () => item.style.background = '#fff');
        item.addEventListener('click', (e) => {
          e.preventDefault();
          e.stopPropagation();
          setLang(code);
          menu.style.display = 'none';
        });
        menu.appendChild(item);
      });
      pill.appendChild(menu);

      pill.addEventListener('click', (e) => {
        e.preventDefault();
        e.stopPropagation();
        document.querySelectorAll('.lang-menu').forEach(m => { if (m !== menu) m.style.display = 'none'; });
        menu.style.display = menu.style.display === 'none' ? 'block' : 'none';
      });
    });
    document.addEventListener('click', () => {
      document.querySelectorAll('.lang-menu').forEach(m => m.style.display = 'none');
    });
  }

  document.addEventListener('DOMContentLoaded', () => {
    buildSwitcher();
    applyTranslations();
  });
})();
